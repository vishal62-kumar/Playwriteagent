"""Step 4: turn validated scenarios into a pytest file.

The code is produced by a template, not by the LLM, so it is always syntactically valid and
every selector comes from the verified inventory. Re-rendering after a re-scan updates all
selectors automatically (this is most of what "healing" needs).
"""
import pprint

from . import config

HEADER = '''"""AUTO-GENERATED by run_agent.py - do not edit by hand (edit scenarios.json in the same folder and re-run it).
Page: {page}
Generated: {generated}
"""
import pytest

PAGE_URL = {url!r}

# Verified selectors from inventory/{slug}.json (scanned {scanned})
ELEMENTS = {elements}

VALIDATORS = {validators}
'''

STEP_CALL = {
    "fill": "qa.fill({element!r}, {value!r})",
    "clear": "qa.clear({element!r})",
    "select": "qa.select({element!r}, {value!r})",
    "check": "qa.check({element!r})",
    "uncheck": "qa.uncheck({element!r})",
    "click": "qa.click({element!r})",
    "press": "qa.press({element!r}, {value!r})",
    "upload": "qa.upload({element!r})",
    "wait": "qa.wait({value!r})",
}
ASSERT_CALL = {
    "validator_fires": "qa.expect_validator_fires({validator!r})",
    "validator_passes": "qa.expect_validator_passes({validator!r})",
    "message_shown": "qa.expect_message({value!r})",
    "element_visible": "qa.expect_visible({element!r})",
    "element_hidden": "qa.expect_hidden({element!r})",
    "element_enabled": "qa.expect_enabled({element!r})",
    "element_disabled": "qa.expect_disabled({element!r})",
    "element_value": "qa.expect_value({element!r}, {value!r})",
    "element_checked": "qa.expect_checked({element!r}, True)",
    "element_unchecked": "qa.expect_checked({element!r}, False)",
    "url_contains": "qa.expect_url_contains({value!r})",
    "no_server_error": "qa.expect_no_server_error()",
}


def _fmt(template, item):
    return template.format(element=item.get("element"), value=item.get("value"), validator=item.get("validator"))


def render(scen_doc: dict, inv: dict, include_writes: bool = True) -> str:
    used_el, used_val = set(), set()
    for sc in scen_doc["scenarios"]:
        for s in sc["steps"]:
            if s.get("element"):
                used_el.add(s["element"])
        for a in sc["assertions"]:
            if a.get("element"):
                used_el.add(a["element"])
            if a.get("validator"):
                used_val.add(a["validator"])

    missing = sorted(k for k in used_el if k not in inv["elements"])
    elements = {k: {"selector": inv["elements"][k]["selector"], "label": inv["elements"][k]["label"]}
                for k in sorted(used_el) if k in inv["elements"]}
    validators = {k: {kk: inv["validators"][k].get(kk) for kk in ("client_id", "message", "kind", "client_side")}
                  for k in sorted(used_val) if k in inv["validators"]}

    slug = config.page_slug(scen_doc["page"])
    out = HEADER.format(
        slug=slug, page=scen_doc["page"], generated=scen_doc["generated_at"], url=inv["url"],
        scanned=inv["scanned_at"], elements=pprint.pformat(elements, width=110, sort_dicts=True),
        validators=pprint.pformat(validators, width=110, sort_dicts=True),
    )
    for sc in scen_doc["scenarios"]:
        uses_missing = [s.get("element") for s in sc["steps"] + sc["assertions"] if s.get("element") in missing]
        meta = {k: sc[k] for k in ("id", "title", "type", "basis", "writes_data")}
        meta["expected"] = "; ".join(_describe(a, inv) for a in sc["assertions"])
        out += "\n\n"
        if uses_missing:
            out += f"@pytest.mark.skip(reason={('Element(s) no longer on the page: ' + ', '.join(uses_missing))!r})\n"
        elif sc["writes_data"] and not include_writes:
            out += "@pytest.mark.skip(reason='Saves data - skipped because saving data was not allowed for this run')\n"
        out += f"@pytest.mark.scenario(**{meta!r})\n"
        out += f"def test_{sc['id']}(qa):\n"
        out += f'    """{sc["title"].replace(chr(34), chr(39))}"""\n'
        out += "    qa.goto(PAGE_URL)\n"
        for s in sc["steps"]:
            out += "    " + _fmt(STEP_CALL[s["action"]], s) + "\n"
        for a in sc["assertions"]:
            out += "    " + _fmt(ASSERT_CALL[a["type"]], a) + "\n"
    compile(out, "generated", "exec")  # guarantees the file is valid Python
    return out


def _describe(a, inv):
    t = a["type"]
    if t == "validator_fires":
        return f"validation '{inv['validators'].get(a['validator'], {}).get('message') or a['validator']}' is shown"
    if t == "validator_passes":
        return f"no '{inv['validators'].get(a['validator'], {}).get('message') or a['validator']}' error"
    if t == "message_shown":
        return f"message '{a['value']}' appears"
    if t == "no_server_error":
        return "no server error"
    label = inv["elements"].get(a.get("element"), {}).get("label") or a.get("element")
    return {
        "element_visible": f"'{label}' is visible", "element_hidden": f"'{label}' is hidden",
        "element_enabled": f"'{label}' is enabled", "element_disabled": f"'{label}' is disabled",
        "element_value": f"'{label}' = '{a.get('value')}'", "element_checked": f"'{label}' is ticked",
        "element_unchecked": f"'{label}' is unticked", "url_contains": f"URL contains '{a.get('value')}'",
    }.get(t, t)


def write(scen_doc: dict, inv: dict, include_writes: bool = True, path=None):
    if path is None:
        config.TESTS_DIR.mkdir(parents=True, exist_ok=True)
        path = config.TESTS_DIR / f"test_{config.page_slug(scen_doc['page'])}.py"
    path.write_text(render(scen_doc, inv, include_writes), encoding="utf-8")
    return path
